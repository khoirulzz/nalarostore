const photo = (file: string) => `/images/nalaro-fashion/${file}.webp`;
const existing = (file: string) => `/images/batiknalaro/${file}.webp`;
const sizes = ["S", "M", "L", "XL"];
function product(
  id: string,
  slug: string,
  name: string,
  category: string,
  price: number,
  image: string,
  description: string,
  stock: number[],
  options = sizes,
  gallery: { url: string; alt: string }[] = [],
): Product {
  return {
    id,
    slug,
    name,
    category,
    price_idr: price,
    primary_image_url: image,
    description,
    gallery,
    status: "active",
    variants: options.map((label, index) => ({
      id: `${id}-${index + 1}`,
      sku: `NF-${id.toUpperCase()}-${index + 1}`,
      option_label: label,
      price_override_idr: null,
      stock_qty: stock[index] || 0,
      reserved_qty: 0,
      available_stock: stock[index] || 0,
      status: "active",
    })),
  };
}
